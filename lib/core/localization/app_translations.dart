  const AppTranslations._();

  static String text(BuildContext context, String source) {
    final languageCode = Localizations.localeOf(context).languageCode;
    if (languageCode == 'en') return source;
    final translations = languageCode == 'ms' ? _ms : _zh;
    return translations[source] ?? _translatePattern(source, translations);
  }

  static String _translatePattern(
    String source,
    Map<String, String> translations,
  ) {
    final patterns = <(RegExp, String Function(Match))>[
      (
        RegExp(r'^(\d+) reviews$'),
        (match) => translations['{count} reviews']!.replaceFirst(
          '{count}',
          match.group(1)!,
        ),
      ),
      (
        RegExp(r'^(\d+) journeys$'),
        (match) => translations['{count} journeys']!.replaceFirst(
          '{count}',
          match.group(1)!,
        ),
      ),
      (
        RegExp(r'^(\d+) steps recorded today$'),
        (match) => translations['{count} steps recorded today']!.replaceFirst(
          '{count}',
          match.group(1)!,
        ),
      ),
      (
        RegExp(r'^Welcome back, (.+)!$'),
        (match) => translations['Welcome back, {name}!']!.replaceFirst(
          '{name}',
          match.group(1)!,
        ),
      ),
    ];
    for (final (pattern, replacement) in patterns) {
      final match = pattern.firstMatch(source);
      if (match != null) return replacement(match);
    }
    return source;
  }

